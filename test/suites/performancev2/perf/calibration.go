// Calibration is the evidence behind a provider's levels: baseline statistics per phase and metric, and the
// value each planted regression reached. It is generated by cmd/calibrate and checked in, so the
// inventory and Validate can show and enforce why a bound is what it is.

type Calibration struct {
	Provider  string                               `json:"provider"`
	Source    string                               `json:"source"`
	Baseline  string                               `json:"baseline_commit"`
	Generated time.Time                            `json:"generated"`
	Phases    map[string]map[string]MetricEvidence `json:"phases"`
	// Kinds is each phase's Result kind, which picks the metrics SuggestLevels gates.
	Kinds map[string]string `json:"kinds,omitempty"`

	// provenance is "source, baseline, generated" by scenario.
	provenance map[string]string
}

type MetricEvidence struct {
	N         int     `json:"n"`
	Median    float64 `json:"median"`
	Min       float64 `json:"min"`
	Max       float64 `json:"max"`
	CV        float64 `json:"cv"`
	Suggested float64 `json:"suggested_bound"`
	// Variants are planted regressions' median values; breaching a bound is a catch.
	Variants map[string]float64 `json:"variants,omitempty"`
	// Controls are negative controls' values. They never count as a catch, a Stable bound they breach fails
	// CheckEvidence, and SuggestBound counts them as baselines.
	Controls map[string]float64 `json:"controls,omitempty"`
}

// DefaultControls are the perf/regressions patches with no performance effect.
var DefaultControls = []string{"rv2013", "rv2008"}

// Promotion rules Validate enforces on Stable gates.
const (
	StableMinRuns = 3
	StableMaxCV   = 0.20
	StableMaxFPR  = 0.01
)

func MustLoadCalibration(b []byte) *Calibration {
	c := &Calibration{}
	if err := json.Unmarshal(b, c); err != nil {
		panic(fmt.Sprintf("loading calibration: %v", err))
	}
	return c
}

// MustLoadCalibrations merges the calibration files matching patterns, such as calibration/<provider>.json and
// calibration/<provider>/*.json. A phase in two files panics, so stale evidence can't shadow a recalibration.
func MustLoadCalibrations(fsys fs.FS, patterns ...string) *Calibration {
	out := &Calibration{Phases: map[string]map[string]MetricEvidence{}, Kinds: map[string]string{}, provenance: map[string]string{}}
	from := map[string]string{}
	for _, pattern := range patterns {
		paths, err := fs.Glob(fsys, pattern)
		if err != nil {
			panic(fmt.Sprintf("loading calibrations %s: %v", pattern, err))
		}
		for _, p := range paths {
			b, err := fs.ReadFile(fsys, p)
			if err != nil {
				panic(fmt.Sprintf("loading calibration %s: %v", p, err))
			}
			c := MustLoadCalibration(b)
			out.Provider = c.Provider
			for id, ev := range c.Phases {
				if prev, ok := from[id]; ok {
					panic(fmt.Sprintf("calibration for %s is in both %s and %s; remove the stale one", id, prev, p))
				}
				from[id], out.Phases[id] = p, ev
				name, _, _ := strings.Cut(id, "/")
				out.provenance[name] = c.provenanceLine()
			}
			maps.Copy(out.Kinds, c.Kinds)
		}
	}
	if len(from) == 0 {
		panic(fmt.Sprintf("no calibration files match %v", patterns))
	}
	return out
}

func (c *Calibration) provenanceLine() string {
	return fmt.Sprintf("%s, baseline %s, generated %s", c.Source, c.Baseline, c.Generated.Format("2006-01-02"))
}

// Provenance returns "source, baseline, generated" for each scenario the calibration covers.
func (c *Calibration) Provenance() map[string]string {
	if c == nil {
		return nil
	}
	if c.provenance != nil {
		return c.provenance
	}
	if c.Source == "" {
		return nil
	}
	out := map[string]string{}
	for id := range c.Phases {
		name, _, _ := strings.Cut(id, "/")
		out[name] = c.provenanceLine()
	}
	return out
}

// ByScenario splits the calibration into one Calibration per scenario, as cmd/calibrate -out writes them.
func (c *Calibration) ByScenario() map[string]*Calibration {
	out := map[string]*Calibration{}
	for id, ev := range c.Phases {
		name, _, _ := strings.Cut(id, "/")
		if out[name] == nil {
			out[name] = &Calibration{Provider: c.Provider, Source: c.Source, Baseline: c.Baseline, Generated: c.Generated,
				Phases: map[string]map[string]MetricEvidence{}, Kinds: map[string]string{}}
		}
		out[name].Phases[id] = ev
		if k, ok := c.Kinds[id]; ok {
			out[name].Kinds[id] = k
		}
	}
	return out
}

func (c *Calibration) evidence(id, metric string) (MetricEvidence, bool) {
	if c == nil {
		return MetricEvidence{}, false
	}
	e, ok := c.Phases[id][metric]
	return e, ok
}

func breaches(m Metric, v, bound float64) bool {
	if m.Upper {
		return v >= bound
	}
	return v <= bound
}

// catches lists the planted regressions that breach the bound, with their change from the baseline median.
func (e MetricEvidence) catches(m Metric, bound float64) []string {
	var out []string
	for name, v := range e.Variants {
		if breaches(m, v, bound) {
			delta := 0.0
			if e.Median != 0 {
				delta = (v - e.Median) / e.Median * 100
			}
			out = append(out, fmt.Sprintf("%s (%+.0f%%)", name, delta))
		}
	}
	sort.Strings(out)
	return out
}

// The power model behind MDE, FPR and RunsFor: one run of a metric is normal around the baseline median with the
// baseline CV, and a regression of d scales its mean and spread by 1+d (by 1-d for metrics gated from below).

func phi(x float64) float64    { return 0.5 * math.Erfc(-x/math.Sqrt2) }
func phiInv(p float64) float64 { return -math.Sqrt2 * math.Erfcinv(2*p) }

// MDE is the smallest regression one run breaches the bound with the given power.
func (e MetricEvidence) MDE(m Metric, bound, power float64) float64 {
	mu, sd, z := e.Median, e.CV*e.Median, phiInv(power)
	if m.Upper {
		if mu-z*sd <= 0 {
			return math.Inf(1)
		}
		return math.Max(0, bound/(mu-z*sd)-1)
	}
	return math.Max(0, 1-bound/(mu+z*sd))
}

// FPR is the chance a baseline run breaches the bound.
func (e MetricEvidence) FPR(m Metric, bound float64) float64 {
	mu, sd := e.Median, e.CV*e.Median
	if sd == 0 {
		return lo.Ternary(breaches(m, mu, bound), 1.0, 0.0)
	}
	if m.Upper {
		return 1 - phi((bound-mu)/sd)
	}
	return phi((bound - mu) / sd)
}

// RunsFor is the runs per side a base-vs-head comparison of means needs to catch a regression of mde with the given
// power and false positive rate, for a metric with this CV.
func RunsFor(cv, mde, fpr, power float64) int {
	if mde <= 0 {
		return 0
	}
	z := (phiInv(1-fpr) + phiInv(power)) * cv / mde
	return max(1, int(math.Ceil(2*z*z)))
}

// Calibrate reduces a directory of reports into a Calibration. A report's parent directory names its run: base-* are
// baselines, <patch> or reg-<patch> are regressions, and patches in controls are negative controls.
func Calibrate(dir string, p *Provider, source string, controls ...string) (*Calibration, error) {
	provider := p.Name
	runs, err := readReports(dir, provider)
	if err != nil {
		return nil, err
	}
	base := map[string]map[string][]float64{}
	variants := map[string]map[string]map[string][]float64{}
	commit, kinds := "", map[string]string{}
	for _, run := range runs {
		kinds[run.result.ID] = run.result.Kind
		for _, m := range p.metrics() {
			if strings.HasPrefix(run.name, "base") {
				add(base, run.result.ID, m.Name, m.Value(run.result))
				if commit == "" {
					commit = run.result.Commit
				}
				continue
			}
			if variants[run.result.ID] == nil {
				variants[run.result.ID] = map[string]map[string][]float64{}
			}
			add(variants[run.result.ID], m.Name, strings.TrimPrefix(run.name, "reg-"), m.Value(run.result))
		}
	}
	c := &Calibration{Provider: provider, Source: source, Baseline: commit, Generated: time.Now().UTC().Truncate(time.Second),
		Phases: map[string]map[string]MetricEvidence{}, Kinds: kinds}
	for phase, byMetric := range base {
		if ev := phaseEvidence(p.metrics(), byMetric, variants[phase], controls); len(ev) > 0 {
			c.Phases[phase] = ev
		}
	}
	return c, nil
}

func phaseEvidence(metrics []Metric, base map[string][]float64, variants map[string]map[string][]float64, controls []string) map[string]MetricEvidence {
	out := map[string]MetricEvidence{}
	for _, m := range metrics {
		if vals := base[m.Name]; len(vals) > 0 && !allZero(vals) {
			out[m.Name] = evidenceFor(m, vals, variants[m.Name], controls)
		}
	}
	return out
}

type runReport struct {
	name   string
	result *Result
}

func readReports(dir, provider string) ([]runReport, error) {
	var paths []string
	if err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() && strings.HasSuffix(path, "_performance_report.json") {
			paths = append(paths, path)
		}
		return err
	}); err != nil {
		return nil, err
	}
	var out []runReport
	for _, path := range paths {
		b, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			return nil, err
		}
		r := &Result{}
		if err := json.Unmarshal(b, r); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if r.ID == "" {
			r.ID = r.Phase
		}
		if r.Provider == provider {
			out = append(out, runReport{name: filepath.Base(filepath.Dir(path)), result: r})
		}
	}
	return out, nil
}

func add(m map[string]map[string][]float64, k1, k2 string, v float64) {
	if m[k1] == nil {
		m[k1] = map[string][]float64{}
	}
	m[k1][k2] = append(m[k1][k2], v)
}

func evidenceFor(m Metric, vals []float64, variants map[string][]float64, controls []string) MetricEvidence {
	e := summarize(vals)
	for name, vs := range variants {
		dst := &e.Variants
		if lo.Contains(controls, name) {
			dst = &e.Controls
		}
		if *dst == nil {
			*dst = map[string]float64{}
		}
		(*dst)[name] = round3(median(vs))
	}
	e.Suggested = SuggestBound(m, e)
	return e
}

func summarize(v []float64) MetricEvidence {
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	mean := 0.0
	for _, x := range s {
		mean += x
	}
	mean /= float64(len(s))
	sd := 0.0
	for _, x := range s {
		sd += (x - mean) * (x - mean)
	}
	sd = math.Sqrt(sd / float64(len(s)))
	cv := 0.0
	if mean != 0 {
		cv = sd / mean
	}
	return MetricEvidence{N: len(s), Median: round3(median(s)), Min: round3(s[0]), Max: round3(s[len(s)-1]), CV: round3(cv)}
}

func median(v []float64) float64 {
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	if len(s)%2 == 1 {
		return s[len(s)/2]
	}
	return (s[len(s)/2-1] + s[len(s)/2]) / 2
}

func allZero(v []float64) bool {
	for _, x := range v {
		if x != 0 {
			return false
		}
	}
	return true
}

func round3(v float64) float64 { return math.Round(v*1000) / 1000 }
