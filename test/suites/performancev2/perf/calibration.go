// Calibration is the evidence behind a provider's levels: baseline statistics per phase and metric, and the
// value each planted regression reached. It is generated by `make perf-calibrate` and checked in, so the
// inventory and Validate can show and enforce why a bound is what it is.
type Calibration struct {
	Provider  string                               `json:"provider"`
	Source    string                               `json:"source"`
	Baseline  string                               `json:"baseline_commit"`
	Generated time.Time                            `json:"generated"`
	Phases    map[string]map[string]MetricEvidence `json:"phases"`
}

type MetricEvidence struct {
	N         int                `json:"n"`
	Median    float64            `json:"median"`
	Min       float64            `json:"min"`
	Max       float64            `json:"max"`
	CV        float64            `json:"cv"`
	Suggested float64            `json:"suggested_bound"`
	Variants  map[string]float64 `json:"variants,omitempty"`
}

// Promotion rules Validate enforces on Stable gates.
const (
	StableMinRuns = 3
	StableMaxCV   = 0.20
)

func MustLoadCalibration(b []byte) *Calibration {
	c := &Calibration{}
	if err := json.Unmarshal(b, c); err != nil {
		panic(fmt.Sprintf("loading calibration: %v", err))
	}
	return c
}

func (c *Calibration) evidence(id, metric string) (MetricEvidence, bool) {
	if c == nil {
		return MetricEvidence{}, false
	}
	e, ok := c.Phases[id][metric]
	return e, ok
}

func breaches(m Metric, v, bound float64) bool {
	if m.Upper {
		return v >= bound
	}
	return v <= bound
}

// catches lists the planted regressions whose value breaches the bound, with their change from the baseline median.
func (e MetricEvidence) catches(m Metric, bound float64) []string {
	var out []string
	for name, v := range e.Variants {
		if breaches(m, v, bound) {
			delta := 0.0
			if e.Median != 0 {
				delta = (v - e.Median) / e.Median * 100
			}
			out = append(out, fmt.Sprintf("%s (%+.0f%%)", name, delta))
		}
	}
	sort.Strings(out)
	return out
}

func (e MetricEvidence) headroom(m Metric, bound float64) float64 {
	if e.Median == 0 || bound == 0 {
		return 0
	}
	if m.Upper {
		return bound / e.Median
	}
	return e.Median / bound
}

// Calibrate reduces a directory of reports into a Calibration. Subdirectories named base-* are baselines;
// any other subdirectory is a planted regression named after the directory.
func Calibrate(dir, provider, source string) (*Calibration, error) {
	runs, err := readReports(dir, provider)
	if err != nil {
		return nil, err
	}
	base := map[string]map[string][]float64{}
	variants := map[string]map[string]map[string][]float64{}
	commit := ""
	for _, run := range runs {
		for _, m := range Metrics {
			if strings.HasPrefix(run.name, "base") {
				add(base, run.result.Phase, m.Name, m.Value(run.result))
				if commit == "" {
					commit = run.result.Commit
				}
				continue
			}
			if variants[run.result.Phase] == nil {
				variants[run.result.Phase] = map[string]map[string][]float64{}
			}
			add(variants[run.result.Phase], m.Name, strings.TrimPrefix(run.name, "reg-"), m.Value(run.result))
		}
	}
	c := &Calibration{Provider: provider, Source: source, Baseline: commit, Generated: time.Now().UTC().Truncate(time.Second), Phases: map[string]map[string]MetricEvidence{}}
	for phase, byMetric := range base {
		if ev := phaseEvidence(byMetric, variants[phase]); len(ev) > 0 {
			c.Phases[phase] = ev
		}
	}
	return c, nil
}

func phaseEvidence(base map[string][]float64, variants map[string]map[string][]float64) map[string]MetricEvidence {
	out := map[string]MetricEvidence{}
	for _, m := range Metrics {
		if vals := base[m.Name]; len(vals) > 0 && !allZero(vals) {
			out[m.Name] = evidenceFor(m, vals, variants[m.Name])
		}
	}
	return out
}

type runReport struct {
	name   string
	result *Result
}

func readReports(dir, provider string) ([]runReport, error) {
	var paths []string
	if err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() && strings.HasSuffix(path, "_performance_report.json") {
			paths = append(paths, path)
		}
		return err
	}); err != nil {
		return nil, err
	}
	var out []runReport
	for _, path := range paths {
		b, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			return nil, err
		}
		r := &Result{}
		if err := json.Unmarshal(b, r); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if r.Provider == provider {
			out = append(out, runReport{name: filepath.Base(filepath.Dir(path)), result: r})
		}
	}
	return out, nil
}

func add(m map[string]map[string][]float64, k1, k2 string, v float64) {
	if m[k1] == nil {
		m[k1] = map[string][]float64{}
	}
	m[k1][k2] = append(m[k1][k2], v)
}

func evidenceFor(m Metric, vals []float64, variants map[string][]float64) MetricEvidence {
	e := summarize(vals)
	if m.Upper {
		e.Suggested = round3(e.Max * 1.1)
	} else {
		e.Suggested = round3(e.Min * 0.9)
	}
	for name, vs := range variants {
		if e.Variants == nil {
			e.Variants = map[string]float64{}
		}
		e.Variants[name] = round3(median(vs))
	}
	return e
}

func summarize(v []float64) MetricEvidence {
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	mean := 0.0
	for _, x := range s {
		mean += x
	}
	mean /= float64(len(s))
	sd := 0.0
	for _, x := range s {
		sd += (x - mean) * (x - mean)
	}
	sd = math.Sqrt(sd / float64(len(s)))
	cv := 0.0
	if mean != 0 {
		cv = sd / mean
	}
	return MetricEvidence{N: len(s), Median: round3(median(s)), Min: round3(s[0]), Max: round3(s[len(s)-1]), CV: round3(cv)}
}

func median(v []float64) float64 {
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	if len(s)%2 == 1 {
		return s[len(s)/2]
	}
	return (s[len(s)/2-1] + s[len(s)/2]) / 2
}

func allZero(v []float64) bool {
	for _, x := range v {
		if x != 0 {
			return false
		}
	}
	return true
}

func round3(v float64) float64 { return math.Round(v*1000) / 1000 }
